CREATE TABLE accounts (
 vpa VARCHAR(255) PRIMARY KEY,
 holder_name VARCHAR(255) NOT NULL,
 balance NUMERIC(19,2) NOT NULL CHECK (balance >= 0),
 device_public_key VARCHAR(512),
 version BIGINT
);
CREATE TABLE transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 packet_hash VARCHAR(64) NOT NULL UNIQUE,
 sender_vpa VARCHAR(255) NOT NULL REFERENCES accounts(vpa),
 receiver_vpa VARCHAR(255) NOT NULL REFERENCES accounts(vpa),
 nonce VARCHAR(64) NOT NULL,
 amount NUMERIC(19,2) NOT NULL CHECK (amount > 0),
 signed_at TIMESTAMP WITH TIME ZONE NOT NULL,
 settled_at TIMESTAMP WITH TIME ZONE NOT NULL,
 bridge_node_id VARCHAR(255) NOT NULL,
 hop_count INTEGER NOT NULL,
 status VARCHAR(255) NOT NULL CHECK (status IN ('SETTLED','REJECTED')),
 CONSTRAINT uq_sender_nonce UNIQUE(sender_vpa, nonce)
);
